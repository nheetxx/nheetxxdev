create table if not exists public.guestbook_entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  author_name text not null check (char_length(author_name) between 1 and 60),
  message text not null check (char_length(message) between 2 and 500),
  created_at timestamptz not null default now()
);

create index if not exists guestbook_entries_created_at_idx
  on public.guestbook_entries (created_at desc);

alter table public.guestbook_entries enable row level security;

grant select on public.guestbook_entries to anon, authenticated;
grant insert on public.guestbook_entries to authenticated;

drop policy if exists "Guestbook entries are publicly readable"
  on public.guestbook_entries;
create policy "Guestbook entries are publicly readable"
  on public.guestbook_entries
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Authenticated users can post guestbook entries"
  on public.guestbook_entries;
create policy "Authenticated users can post guestbook entries"
  on public.guestbook_entries
  for insert
  to authenticated
  with check (auth.uid() = user_id);
