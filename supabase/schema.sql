create table if not exists public.guestbook_entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  author_name text not null check (char_length(author_name) between 1 and 60),
  author_avatar_url text,
  is_owner boolean not null default false,
  parent_id bigint references public.guestbook_entries (id) on delete cascade,
  message text not null check (char_length(message) between 2 and 500),
  created_at timestamptz not null default now()
);

alter table public.guestbook_entries
  add column if not exists author_avatar_url text;

alter table public.guestbook_entries
  add column if not exists is_owner boolean not null default false;

alter table public.guestbook_entries
  add column if not exists parent_id bigint references public.guestbook_entries (id) on delete cascade;

update public.guestbook_entries as entry
set author_avatar_url = case
  when coalesce(
    auth_user.raw_user_meta_data ->> 'avatar_url',
    auth_user.raw_user_meta_data ->> 'picture'
  ) like 'https://%'
    then coalesce(
      auth_user.raw_user_meta_data ->> 'avatar_url',
      auth_user.raw_user_meta_data ->> 'picture'
    )
  else null
end
from auth.users as auth_user
where entry.user_id = auth_user.id
  and entry.author_avatar_url is null;

update public.guestbook_entries as entry
set is_owner = coalesce(lower(auth_user.email) = 'fnaufal.dev@gmail.com', false)
from auth.users as auth_user
where entry.user_id = auth_user.id
  and entry.is_owner is distinct from coalesce(lower(auth_user.email) = 'fnaufal.dev@gmail.com', false);

create or replace function public.set_guestbook_entry_owner()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.parent_id is not null and not exists (
    select 1
    from public.guestbook_entries as parent
    where parent.id = new.parent_id
      and parent.parent_id is null
  ) then
    raise exception 'Replies must reference a top-level guestbook entry.';
  end if;

  new.is_owner := exists (
    select 1
    from auth.users as auth_user
    where auth_user.id = auth.uid()
      and lower(auth_user.email) = 'fnaufal.dev@gmail.com'
  );
  return new;
end;
$$;

drop trigger if exists set_guestbook_entry_owner on public.guestbook_entries;
create trigger set_guestbook_entry_owner
  before insert on public.guestbook_entries
  for each row
  execute function public.set_guestbook_entry_owner();

create index if not exists guestbook_entries_created_at_idx
  on public.guestbook_entries (created_at desc);

create index if not exists guestbook_entries_parent_created_at_idx
  on public.guestbook_entries (parent_id, created_at)
  where parent_id is not null;

create table if not exists public.guestbook_entry_reactions (
  entry_id bigint not null references public.guestbook_entries (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  emoji text not null check (char_length(emoji) between 1 and 16),
  created_at timestamptz not null default now(),
  primary key (entry_id, user_id, emoji)
);

alter table public.guestbook_entry_reactions enable row level security;

grant select, insert, delete on public.guestbook_entry_reactions to authenticated;

drop policy if exists "Users can read their own guestbook reactions"
  on public.guestbook_entry_reactions;
create policy "Users can read their own guestbook reactions"
  on public.guestbook_entry_reactions
  for select
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists "Authenticated users can react to guestbook entries"
  on public.guestbook_entry_reactions;
create policy "Authenticated users can react to guestbook entries"
  on public.guestbook_entry_reactions
  for insert
  to authenticated
  with check (auth.uid() = user_id);

drop policy if exists "Users can remove their own guestbook reactions"
  on public.guestbook_entry_reactions;
create policy "Users can remove their own guestbook reactions"
  on public.guestbook_entry_reactions
  for delete
  to authenticated
  using (auth.uid() = user_id);

drop view if exists public.guestbook_entry_reaction_counts;

create or replace function public.get_guestbook_entry_reaction_counts(p_entry_ids bigint[])
returns table (entry_id bigint, emoji text, count integer)
language sql
security definer
set search_path = ''
as $$
  select reaction.entry_id, reaction.emoji, count(*)::integer
  from public.guestbook_entry_reactions as reaction
  where p_entry_ids is not null
    and reaction.entry_id = any(p_entry_ids)
  group by reaction.entry_id, reaction.emoji;
$$;

revoke all on function public.get_guestbook_entry_reaction_counts(bigint[]) from public;
grant execute on function public.get_guestbook_entry_reaction_counts(bigint[]) to anon, authenticated;

alter table public.guestbook_entries enable row level security;

